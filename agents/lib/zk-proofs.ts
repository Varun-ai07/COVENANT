// Initialize Lit client for encrypted communications if needed
let litClient: LitJsSdk.LitNodeClient | null = null;

/**
 * Initialize Lit Protocol client for ZK proof communications
 */
export async function initLitForZK(): Promise<void> {
  if (litClient) {
    return; // Already initialized
  }
  
  litClient = new LitJsSdk.LitNodeClient({
    alertWhenUnauthorized: false,
    litNetwork: "datil-test", // Use datil testnet for development
    debug: false,
  });
  
  await litClient.connect();
}

